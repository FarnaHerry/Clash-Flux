#!/usr/bin/env python3
"""Regenerate the light and dark navigation glyphs from the selected SVGs."""

from pathlib import Path
from xml.etree import ElementTree as ET


IMAGES = Path(__file__).resolve().parents[1] / "resources" / "images"
SVG_NS = "http://www.w3.org/2000/svg"
ICONS = {
    "home": "home_selected",
    "request": "request_selected",
    "proxies": "proxies_selected",
    "route": "route_selected",
    "connections": "connections_selected",
    "logs": "logs_selected",
    "website_test": "website_test_selected",
    "gear": "gear",
}
PALETTES = {
    "light": ("#66599B", "#996314", "#197E56", "#2767C4", "#C54461"),
    "dark": ("#BECAF2", "#FFD28B", "#7ADCAE", "#91BDFF", "#FFA0AA"),
}
# Values are in the icons' shared 24-unit view box, ordered back to front.
FIELDS = (
    ("gold", "0.48 12.48", "19.68 24.96", "0.80"),
    ("green", "12 24", "18.72 21.12", "0.79"),
    ("blue", "23.52 11.52", "19.68 24.96", "0.80"),
    ("red", "12 0.96", "18.72 21.12", "0.78"),
)


def generate(source, palette):
    root = ET.Element("svg", {"xmlns": SVG_NS, "width": "24", "height": "24", "viewBox": source.attrib["viewBox"]})
    root.append(ET.Comment(" Generated by scripts/generate-navigation-gradients.py. "))
    definitions = ET.SubElement(root, "defs")
    filled = ET.SubElement(definitions, "g", {"id": "glyph"})
    strokes = []
    for original in source:
        shape = ET.Element(original.tag.removeprefix(f"{{{SVG_NS}}}"), original.attrib)
        if shape.get("stroke", "none") != "none":
            # The route icon includes linework as well as filled shapes.
            del shape.attrib["stroke"]
            shape_id = f"line-{len(strokes)}"
            shape.set("id", shape_id)
            definitions.append(shape)
            strokes.append(shape_id)
        else:
            shape.attrib.pop("fill", None)
            filled.append(shape)

    for (name, center, radius, end), color in zip(FIELDS, palette[1:], strict=True):
        gradient = ET.SubElement(definitions, "radialGradient", {
            "id": name, "gradientUnits": "userSpaceOnUse", "cx": "0", "cy": "0", "r": "1",
            "gradientTransform": f"translate({center}) scale({radius})",
        })
        ET.SubElement(gradient, "stop", {"offset": "0", "stop-color": color})
        ET.SubElement(gradient, "stop", {"offset": end, "stop-color": color, "stop-opacity": "0"})

    for paint in (palette[0], *(f"url(#{field[0]})" for field in FIELDS)):
        ET.SubElement(root, "use", {"href": "#glyph", "fill": paint})
        for shape_id in strokes:
            ET.SubElement(root, "use", {"href": f"#{shape_id}", "stroke": paint})

    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode") + "\n"


if __name__ == "__main__":
    for name, original in ICONS.items():
        source = ET.parse(IMAGES / f"{original}.svg").getroot()
        for mode, palette in PALETTES.items():
            (IMAGES / f"nav_{name}_gradient_{mode}.svg").write_text(
                generate(source, palette), encoding="utf-8"
            )

#!/usr/bin/env python3
"""Export project logos and native icons from assets/branding/logo.svg.

Requires CairoSVG and Pillow only when regenerating; builds consume the checked-in
assets. --check compares every generated byte without changing the workspace.
"""

import argparse
from copy import deepcopy
from io import BytesIO
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)


def svg_variant(master, palette, title):
    svg = deepcopy(master)
    # Retain the established UI framing instead of the animation's full canvas.
    svg.set("viewBox", "7 18 114 102")
    svg.set("width", "128")
    svg.set("height", "128")
    caption = svg.find(f"{{{NS}}}title")
    if caption is None:
        caption = ET.Element(f"{{{NS}}}title")
        svg.insert(0, caption)
    caption.text = title
    for element in svg.iter():
        for key in ("fill", "stroke"):
            if element.get(key) in palette:
                element.set(key, palette[element.get(key)])
    ET.indent(svg)
    return ET.tostring(svg, encoding="utf-8") + b"\n"


def raster(svg, size, background=None):
    image = Image.open(BytesIO(cairosvg.svg2png(
        bytestring=svg, output_width=size, output_height=size))).convert("RGBA")
    if background is not None:
        canvas = Image.new("RGBA", image.size, background)
        canvas.alpha_composite(image)
        return canvas.convert("RGB")
    return image


def encode(image, kind="PNG", **options):
    output = BytesIO()
    image.save(output, format=kind, **options)
    return output.getvalue()


def exports(tray_only=False):
    master = ET.parse(ROOT / "assets/branding/logo.svg").getroot()
    output = {}
    for name, color in [("tray_default", "#253851"), ("tray_tun", "#0BAA9E"),
                        ("tray_system_proxy", "#7451C2")]:
        vector = svg_variant(master, {
            "#111318": color, "#e8edf0": "#ffffff", "#626a75": color},
            "Clash-Flux tray mark, complete cat and box")
        if name == "tray_default":
            output["assets/tray/logo.svg"] = vector
        for size, suffix in [(32, ""), (64, "@2x"), (96, "@3x")]:
            output[f"resources/images/{name}{suffix}.png"] = encode(raster(vector, size))
    if tray_only:
        return output

    dark = svg_variant(master, {}, "Clash-Flux logo, demo geometry, dark theme")
    light = svg_variant(master, {"#e8edf0": "#fafbfc", "#626a75": "#9aa2ad"},
                        "Clash-Flux logo, demo geometry, light theme")
    for theme, data in [("dark", dark), ("light", light)]:
        output[f"resources/images/clash_flux_logo_vector_{theme}_current.svg"] = data
        # The independent preview uses byte-identical production image resources.
        if (ROOT / "demos/box-cat-demo").is_dir():
            output[f"demos/box-cat-demo/resources/images/project_logo_{theme}.svg"] = data

    output["resources/images/clash_flux_logo.png"] = encode(raster(light, 1254))
    output["assets/icon.png"] = encode(raster(dark, 256))
    ico = raster(dark, 256)
    output["assets/icon.ico"] = encode(ico, "ICO", sizes=[
        (size, size) for size in [16, 24, 32, 48, 64, 128, 256]])
    output["platform/macos/AppIcon.icns"] = encode(raster(dark, 1024), "ICNS")

    android = "platform/android/app/src/main/res"
    output[f"{android}/drawable-nodpi/ic_launcher_mascot.png"] = output[
        "resources/images/clash_flux_logo.png"]
    for density, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
                          ("xxhdpi", 144), ("xxxhdpi", 192)]:
        output[f"{android}/mipmap-{density}/ic_launcher.png"] = encode(
            raster(light, size, "white"))
    output["platform/ios/App/Assets.xcassets/AppIcon.appiconset/AppIcon.png"] = encode(
        raster(light, 1024, "white"))

    sheet = Image.new("RGB", (768, 384), "white")
    sheet.paste(Image.new("RGB", (384, 384), "#1c1b1f"), (384, 0))
    for x, vector in [(0, light), (384, dark)]:
        image = raster(vector, 256)
        sheet.paste(image, (x + 64, 28), image)
        for left, size in [(120, 32), (184, 48)]:
            small = raster(vector, size)
            sheet.paste(small, (x + left, 310), small)
    output["docs/branding/logo-preview.png"] = encode(sheet)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tray-only", action="store_true")
    options = parser.parse_args()
    generated = exports(options.tray_only)
    mismatches = []
    for relative, data in generated.items():
        path = ROOT / relative
        if options.check:
            if not path.is_file() or path.read_bytes() != data:
                mismatches.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatches:
        print("Branding assets differ from the master:", file=sys.stderr)
        print("\n".join(mismatches), file=sys.stderr)
        return 1
    print(f"{'Verified' if options.check else 'Generated'} {len(generated)} branding assets.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
